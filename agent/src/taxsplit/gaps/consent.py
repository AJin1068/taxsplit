def consent_message(person: str, *, adult_child: bool = False) -> str:
    """동의 안내 한 통. 단계는 한 줄에 하나씩(큰 글씨로 읽기 쉽게) 나눈다."""
    # 부르는 말은 사용자가 쓴 이름 그대로("어머니", "엄마")
    lines = [
        f"{person}, 연말정산 자료 제공 동의를 부탁드려요.",
        "동의해 주시면 병원비·카드 사용액 같은 자료를 연말정산에 쓸 수 있어요.",
    ]
    if adult_child:
        # 인쇄 368쪽: 19세가 넘어 성년이 된 자녀는 자녀가 직접 동의해야 한다
        lines.append("19세가 넘으면 본인이 직접 동의해야 자료가 보여요.")
    for _, name, steps in METHODS:
        lines.append("")
        lines.append(name)
        lines += [f"  {i}. {s}" for i, s in enumerate(steps.split(" → "), start=1)]
    lines += ["", "컴퓨터가 어려우시면 세무서 방문", f"  {VISIT_TEXT}", "", CLOSING]
    return "\n".join(lines)
